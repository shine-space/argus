"""Build a local, equal-area particle cloud from Natural Earth's public-domain land polygons."""
import base64
import json
import math
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'site/particle-shapes/ne_110m_land.geojson'
features = json.loads(DATA.read_text(encoding='utf-8'))['features']
polygons = []
for feature in features:
    geometry = feature['geometry']
    for rings in ([geometry['coordinates']] if geometry['type'] == 'Polygon' else geometry['coordinates']):
        exterior = rings[0]
        bounds = (min(p[0] for p in exterior), min(p[1] for p in exterior),
                  max(p[0] for p in exterior), max(p[1] for p in exterior))
        polygons.append((bounds, rings))

def inside_ring(lon, lat, ring):
    result = False
    previous = ring[-1]
    for current in ring:
        x1, y1 = previous
        x2, y2 = current
        if (y1 > lat) != (y2 > lat) and lon < (x2-x1)*(lat-y1)/(y2-y1)+x1:
            result = not result
        previous = current
    return result

def on_land(lon, lat):
    for (left, bottom, right, top), rings in polygons:
        if left <= lon <= right and bottom <= lat <= top and inside_ring(lon, lat, rings[0]):
            return not any(inside_ring(lon, lat, hole) for hole in rings[1:])
    return False

assert on_land(2, 49) and on_land(20, 0) and not on_land(-140, 0)
samples = []
count = 64000
angle = math.pi * (3-math.sqrt(5))
for index in range(count):
    y = 1-2*(index+.5)/count
    lat = math.degrees(math.asin(y))
    lon = math.degrees(index*angle) % 360-180
    land = on_land(lon, lat)
    if land or index % 32 == 0:
        samples.append((round(lon*100), round(lat*100), 0 if land else 2))

# Additional shoreline samples keep coastlines and islands recognizable.
for _, rings in polygons:
    for ring in rings:
        for first, last in zip(ring, ring[1:]):
            dx = last[0]-first[0]
            if abs(dx) > 180:
                continue
            dy = last[1]-first[1]
            distance = math.hypot(dx*math.cos(math.radians((first[1]+last[1])/2)), dy)
            steps = max(1, math.ceil(distance/.6))
            for index in range(steps):
                t = index/steps
                samples.append((round((first[0]+dx*t)*100), round((first[1]+dy*t)*100), 1))

packed = b''.join(struct.pack('<hhB', *sample) for sample in samples)
encoded = base64.b64encode(packed).decode('ascii')
output = ROOT / 'site/particle-shapes/earth-points.mjs'
output.write_text('// Natural Earth 1:110m land, public domain. Generated by scripts/build-earth-points.py.\n'
                  '// Source: https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_110m_land.geojson\n'
                  'export const earthPointData = "'+encoded+'";\n', encoding='utf-8')
print(f'Generated {len(samples)} georeferenced particles ({len(packed)} bytes)')
